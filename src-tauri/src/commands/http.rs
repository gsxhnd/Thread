//! HTTP send/cancel commands: orchestrates variables, execution and history.

use std::sync::Arc;

use serde::Deserialize;
use serde_json::Value;
use tauri::State;

use crate::config::ThreadConfigStore;
use crate::db::{SharedDb, bodies_dir};
use crate::error::{AppError, AppResult};
use crate::services::history::{self, NewHistoryEntry};
use crate::services::http::{
    EffectiveSettings, HttpRequestConfig, HttpResponse, HttpTaskRegistry, SendOptions, execute,
};
use crate::workspace::{SharedWorkspace, files, layout, ops};

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct HttpSendPayload {
    /// Generated by the frontend so the in-flight request can be cancelled.
    pub task_id: String,
    /// Workspace-relative request file path when sending a saved request.
    #[serde(default)]
    pub request_path: Option<String>,
    pub config: HttpRequestConfig,
    #[serde(default)]
    pub environment_path: Option<String>,
    #[serde(default = "default_true")]
    pub save_history: bool,
}

fn default_true() -> bool {
    true
}

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct HttpCancelPayload {
    pub task_id: String,
}

#[derive(Debug, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct HttpCancelResult {
    pub cancelled: bool,
}

#[tauri::command]
pub async fn http_send(
    workspace: State<'_, SharedWorkspace>,
    registry: State<'_, Arc<HttpTaskRegistry>>,
    config_store: State<'_, Arc<ThreadConfigStore>>,
    db: State<'_, SharedDb>,
    payload: HttpSendPayload,
) -> AppResult<HttpResponse> {
    if payload.task_id.trim().is_empty() {
        return Err(AppError::Validation("taskId is required".into()));
    }
    let root = workspace.root()?;
    let app_settings = config_store.app_settings();

    // Collection-level defaults (auth inheritance + request name/document).
    let (collection_auth, request_name, request_document) = match payload.request_path.as_deref() {
        Some(path) => match layout::resolve_inside(&root, path) {
            Ok(absolute) => {
                let (_, meta) = ops::nearest_collection(&root, path);
                let document = files::read_json_value(&absolute).ok();
                let name = document
                    .as_ref()
                    .and_then(|value| value.get("name"))
                    .and_then(|value| value.as_str())
                    .map(str::to_string);
                (meta.as_ref().map(|meta| meta.auth.clone()), name, document)
            }
            // A draft id or a missing file should not block the in-memory request.
            Err(_) => (None, None, None),
        },
        None => (None, None, None),
    };

    let effective_settings =
        EffectiveSettings::resolve(&payload.config.settings, None, &app_settings);

    let config_environment = if payload
        .environment_path
        .as_deref()
        .is_none_or(|value| value.trim().is_empty())
    {
        workspace
            .config()
            .ok()
            .and_then(|config| config.active_environment)
    } else {
        None
    };
    let identifier = payload
        .environment_path
        .as_deref()
        .map(str::trim)
        .filter(|value| !value.is_empty())
        .or_else(|| {
            config_environment
                .as_deref()
                .map(str::trim)
                .filter(|value| !value.is_empty())
        });
    let explicit = payload
        .environment_path
        .as_deref()
        .is_some_and(|value| !value.trim().is_empty());
    let active_rel = match identifier {
        Some(value) => match ops::resolve_environment_rel(&root, value) {
            Some(rel) => Some(rel),
            None if explicit => {
                return Err(AppError::NotFound(format!(
                    "environment not found: {value}"
                )));
            }
            None => None,
        },
        None => None,
    };
    let variables = ops::resolve_variables(&root, active_rel.as_deref())?;

    let receiver = registry.register(&payload.task_id);
    let options = SendOptions {
        task_id: payload.task_id.clone(),
        config: payload.config.clone(),
        variables,
        collection_auth: collection_auth.clone().filter(|auth| !auth.is_none_type()),
        settings: effective_settings,
        bodies_dir: bodies_dir(),
    };

    let outcome = execute(options, Some(receiver)).await;
    registry.unregister(&payload.task_id);
    let (response, resolved) = outcome?;

    if payload.save_history {
        let _ = save_history(
            db.inner(),
            &root,
            &payload,
            &response,
            &resolved,
            request_name.as_deref(),
            request_document,
            app_settings.history_limit,
        );
    }

    Ok(response)
}

#[tauri::command]
pub async fn http_cancel(
    registry: State<'_, Arc<HttpTaskRegistry>>,
    payload: HttpCancelPayload,
) -> AppResult<HttpCancelResult> {
    Ok(HttpCancelResult {
        cancelled: registry.cancel(&payload.task_id),
    })
}

#[tauri::command]
pub async fn http_active_tasks(
    registry: State<'_, Arc<HttpTaskRegistry>>,
) -> AppResult<Vec<String>> {
    Ok(registry.active())
}

#[allow(clippy::too_many_arguments)]
fn save_history(
    db: &crate::db::DbState,
    root: &std::path::Path,
    payload: &HttpSendPayload,
    response: &HttpResponse,
    resolved: &crate::services::http::ResolvedRequest,
    request_name: Option<&str>,
    request_document: Option<Value>,
    history_limit: i64,
) -> AppResult<String> {
    let name = request_name.unwrap_or("Ad-hoc request").to_string();
    let document = request_document
        .unwrap_or_else(|| serde_json::to_value(&payload.config).unwrap_or(Value::Null));

    let request_snapshot = serde_json::json!({
        "protocol": "http",
        "name": name,
        "document": document,
        "resolved": {
            "method": resolved.method,
            "url": resolved.url,
            "headers": resolved.headers,
            "bodyKind": resolved.body_kind,
            "bodyPreview": resolved.body_preview,
        }
    })
    .to_string();

    let response_snapshot = serde_json::json!({
        "statusCode": response.status_code,
        "statusText": response.status_text,
        "headers": response.headers,
        "contentType": response.content_type,
        "bodySize": response.body_size,
        "timing": response.timing,
        "redirectCount": response.redirect_count,
        "url": response.url,
        "unresolvedVariables": response.unresolved_variables,
    })
    .to_string();

    let entry = NewHistoryEntry {
        workspace_path: root.to_string_lossy().into_owned(),
        request_file_path: payload.request_path.clone(),
        protocol: "http".into(),
        name: Some(name),
        method: Some(resolved.method.clone()),
        url: Some(resolved.url.clone()),
        request_snapshot,
        response_snapshot: Some(response_snapshot),
        response_body_path: response.body_file_path.clone(),
        status_code: Some(response.status_code as i64),
        duration_ms: Some(response.timing.total_ms.round() as i64),
    };

    let id = history::insert(db, &entry)?;
    if history_limit > 0 {
        let _ = history::trim(db, &root.to_string_lossy(), history_limit);
    }
    Ok(id)
}

/// Ad-hoc request drafts are not written to disk, so they carry a frontend id.
#[cfg(test)]
mod tests {
    use super::*;
    use crate::services::http::HttpRequestConfig;
    use crate::workspace::formats::AuthSpec;

    #[test]
    fn payload_deserializes_camel_case_from_frontend() {
        let payload: HttpSendPayload = serde_json::from_value(serde_json::json!({
            "taskId": "t-1",
            "requestPath": "api/list.http.json",
            "config": { "method": "GET", "url": "https://example.com" },
            "environmentPath": "environments/dev.env.json"
        }))
        .unwrap();
        assert_eq!(payload.task_id, "t-1");
        assert!(payload.save_history);
        assert_eq!(payload.config.method, "GET");
    }

    #[test]
    fn config_defaults_to_get_without_body() {
        let config: HttpRequestConfig = serde_json::from_value(serde_json::json!({})).unwrap();
        assert_eq!(config.method, "GET");
        assert_eq!(config.body.kind, "none");
        assert!(matches!(
            AuthSpec::resolve(&config.auth, None).kind.as_str(),
            "inherit"
        ));
    }
}
